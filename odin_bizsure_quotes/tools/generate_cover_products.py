def generate_ga():
    w = Writer()
    w.comment("GA Insurance: insurer_ga is the contact the motor rates installed.")
    w.record("categ_ins_ga_community_health", "product.category", [
        ("name", "GA Community Health"),
        ("parent_id", Ref("categ_ins")),
    ])
    cat = Catalogue(w, "categ_ins_ga_community_health")

    w.comment("Maternity at additional premium: one table per limit, shared by every plan.")
    maternity = []
    for index, (limit, premium) in enumerate(rc.GA_MATERNITY):
        key = "ga_mat_%sk" % (limit // 1000)
        maternity.append(cat.table(
            key, "GA Community Maternity – %s per Family" % kes(limit), "maternity",
            "policy", [("GA-MAT-%sK" % (limit // 1000), "any", 0, 0, 0, premium)], limit,
            "Optional – maternity cover (per family; female principal or spouse)",
            benefits="" if index else bullets("Maternity benefits", [
                "Normal delivery, elective and subsequent caesarean sections",
                "10-month waiting period for maternity complications/normal delivery",
            ]),
            sequence=20 + index))

    for index, limit in enumerate(rc.GA_LIMITS):
        short = "%sK" % (limit // 1000) if limit < 1000000 else "%gM" % (limit / 1000000)
        for pandemic, rates in ((False, rc.GA_EXCLUDING_PANDEMIC),
                                (True, rc.GA_INCLUDING_PANDEMIC)):
            variant = "Including Pandemic" if pandemic else "Excluding Pandemic"
            flag = "P" if pandemic else "X"
            key = "ga_ip_%s_%s" % (slug(short), "incl" if pandemic else "excl")
            w.comment("GA Community Health, IP limit %s, %s" % (kes(limit), variant.lower()))
            rows = [("GA-IP-%s-%s-M%s" % (short, flag, size), "any", rc.GA_AGE_MIN,
                     rc.GA_AGE_MAX, size, rates[row][index])
                    for row, size in enumerate(rc.GA_SIZES)]
            table = cat.table(
                key, "GA Community Inpatient – %s – %s" % (kes(limit), variant), "inpatient",
                "family_size", rows, limit,
                "Inpatient – %s per family per year, %s" % (
                    kes(limit), "including pandemic (Covid-19) cover" if pandemic
                    else "excluding pandemic cover"),
                benefits=ga_inpatient_benefits(index, pandemic))
            cat.product(
                key.replace("ga_ip_", "ga_"),
                "GA Community Health – %s – %s" % (kes(limit), variant), "insurer_ga",
                [table] + maternity, GA_TERMS)
    w.write("cover_product_ga.xml")
    return w


