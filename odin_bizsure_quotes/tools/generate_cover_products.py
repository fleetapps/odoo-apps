def level_benefits(title, limit_line, rows, index):
    items = [limit_line]
    for label, values in rows:
        value = values[index] if isinstance(values, list) else values
        if value is not None:
            items.append("%s: %s" % (label, money(value)))
    return bullets(title, items)


