#!/usr/bin/env python3
"""Turn tools/rate_cards.py into Cover Quotes products.

Writes ``data/cover_product_ga.xml`` (Community Health and Hadhi),
``data/cover_product_jubilee.xml``, ``data/cover_product_heritage.xml`` and
``data/cover_product_apa.xml`` (Afya Nafuu):
the insurer, product categories, one rate table (``odin.cover.table``) per
table of the card with one row per person, band or family size, and one
product (``odin.cover.product``) per plan. Saving a product makes its
quotation template, exactly as when the office adds a plan in Cover Quotes ▸
Products, so these plans are quoted the way every other plan is.

Loaded once (noupdate): from then on the rates are the office's, kept in
Cover Quotes ▸ Products.

    python3 tools/generate_cover_products.py
"""

import os
import re
import sys
from xml.sax.saxutils import escape, quoteattr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import key_terms  # noqa: E402
import rate_cards as rc  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "data")
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by tools/generate_cover_products.py from tools/rate_cards.py."
          " Do not edit by hand. -->\n<odoo noupdate=\"1\">\n")
FOOTER = "</odoo>\n"
LEVIES = "[(6, 0, [ref('tax_training_levy'), ref('tax_phcf')])]"

ROLE_CODE = {"principal": "P", "spouse": "S", "child": "C", "any": "A", "dependant": "D"}


def slug(text):
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9]+", "_", text.lower())).strip("_")


def kes(amount):
    return "KES {:,}".format(amount)


def money(value):
    """A benefit value as the card prints it: amounts as KES, words as they are."""
    return kes(value) if isinstance(value, int) else value


def bullets(title, items):
    return "\n".join([title] + ["• %s" % item for item in items])


class Writer:
    """The records of one file, in load order."""

    def __init__(self):
        self.body = []
        self.ids = set()

    def record(self, xmlid, model, fields):
        if xmlid in self.ids:
            raise SystemExit("duplicate external id %s" % xmlid)
        self.ids.add(xmlid)
        out = ['    <record id="%s" model="%s">' % (xmlid, model)]
        for name, value in fields:
            if isinstance(value, Ref):
                out.append('        <field name="%s" ref="%s"/>' % (name, value.xmlid))
            elif isinstance(value, Eval):
                out.append('        <field name="%s" eval=%s/>' % (name, quoteattr(value.expr)))
            elif isinstance(value, Html):
                out.append('        <field name="%s" type="html">%s</field>' % (name, value.markup))
            else:
                out.append('        <field name="%s">%s</field>' % (name, escape(str(value))))
        out.append("    </record>\n")
        self.body.append("\n".join(out))

    def comment(self, text):
        self.body.append("    <!-- %s -->" % escape(text))

    def write(self, filename):
        with open(os.path.join(OUT, filename), "w", encoding="utf-8") as handle:
            handle.write(HEADER + "\n".join(self.body) + FOOTER)


class Ref:
    def __init__(self, xmlid):
        self.xmlid = xmlid


class Eval:
    def __init__(self, expr):
        self.expr = expr


class Html:
    def __init__(self, markup):
        self.markup = markup


def terms(key):
    """The product's key terms (tools/key_terms.py), as its quotations print them."""
    return Html(key_terms.html(key))


class Catalogue:
    """Tables, rows and products, written in the order Odoo must load them."""

    def __init__(self, writer, category):
        self.w = writer
        self.category = category
        self.tables = {}

    def table(self, key, name, cover, basis, rows, limit, section_title, benefits="",
              cover_label="", age_basis="own", partial=False, requires_outpatient=False,
              sequence=10):
        """One table of the card. ``rows``: (code, role, age_min, age_max,
        family_size, premium)."""
        xmlid = "table_%s" % key
        fields = [
            ("name", name),
            ("sequence", sequence),
            ("cover", cover),
            ("basis", basis),
            ("age_basis", age_basis),
            ("partial", Eval("True" if partial else "False")),
            ("limit", limit),
            ("requires_outpatient", Eval("True" if requires_outpatient else "False")),
            ("section_title", section_title),
        ]
        if cover_label:
            fields.append(("cover_label", cover_label))
        if benefits:
            fields.append(("benefits", benefits))
        self.w.record(xmlid, "odin.cover.table", fields)
        for code, role, age_min, age_max, size, premium in rows:
            self.w.record("rate_%s" % slug(code), "product.template", [
                ("name", name),
                ("default_code", code),
                ("odin_cover_table_id", Ref(xmlid)),
                ("odin_row_role", role),
                ("odin_row_age_min", age_min),
                ("odin_row_age_max", age_max),
                ("odin_row_family_size", size),
                ("list_price", premium),
                ("type", "service"),
                ("sale_ok", Eval("True")),
                ("purchase_ok", Eval("False")),
                ("invoice_policy", "order"),
                ("categ_id", Ref(self.category)),
                ("taxes_id", Eval(LEVIES)),
            ])
        self.tables[key] = xmlid
        return xmlid

    def product(self, key, name, insurer, tables, terms, plan_type="family", sequence=10,
                active=True):
        fields = [
            ("name", name),
            ("line", "medical"),
            ("insurer_id", Ref(insurer)),
            ("plan_type", plan_type),
            ("sequence", sequence),
            ("terms", terms),
            ("table_ids", Eval("[(6, 0, [%s])]" % ", ".join("ref('%s')" % t for t in tables))),
        ]
        if not active:
            # Off: in Cover Quotes > Products, not offered in New quote.
            fields.append(("active", Eval("False")))
        self.w.record("cover_%s" % key, "odin.cover.product", fields)


