#!/usr/bin/env python3
"""Turn the extracted BizSure rate cards into Odoo data files.

The JSON under ``data/source`` is the input: products, quotation templates and
their lines, exactly as read from the configured database. Re-running this
script regenerates every XML file in ``data`` deterministically, so a rate
change is a change to the JSON plus one run, never hand-edited XML.

    python3 tools/generate_data.py
"""

import html as htmllib
import json
import os
import re
from xml.sax.saxutils import escape, quoteattr

import key_terms

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)
SOURCE = os.path.join(MODULE, "data", "source")
OUT = os.path.join(MODULE, "data")

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate_data.py. Do not edit by hand. -->\n<odoo>\n'
FOOTER = "</odoo>\n"

#: first "KES 1,234,567" in a section title is the cover limit
KES = re.compile(r"KES\s*([\d,]+)")

#: who underwrites each product line, by the start of the template name. The
#: medical quote builder groups and filters plans by insurer.
INSURERS = (
    ("APA Jamii Plus", "insurer_apa", "APA Insurance"),
    ("Birdview Bizsure Afya", "insurer_birdview", "Birdview Microinsurance"),
)


def slug(value):
    out = re.sub(r"[^a-z0-9]+", "_", (value or "").lower()).strip("_")
    return re.sub(r"_+", "_", out)


def load(name):
    with open(os.path.join(SOURCE, name), encoding="utf-8") as fh:
        return json.load(fh)


def benefit_of(section_name):
    """Derive the client-facing benefit from a section title.

    Returns ``(label, key, cover_limit, is_optional)``. The limit is the first
    KES figure in the title: on Birdview the title also quotes the maternity
    sub-limit, which must not be mistaken for the plan limit.
    """
    name = section_name or ""
    low = name.lower()
    optional = low.startswith("optional")
    limit = 0.0
    found = KES.search(name)
    if found:
        limit = float(found.group(1).replace(",", ""))

    # Match whichever benefit is named FIRST. "Optional - dental cover (per
    # person, with outpatient cover)" is a dental section that merely mentions
    # outpatient; a fixed precedence would file it under Outpatient.
    needles = (
        ("inpatient", "Inpatient"),
        ("outpatient", "Outpatient"),
        ("maternity", "Maternity"),
        ("dental", "Dental"),
        ("optical", "Optical"),
        ("rider", "Riders"),
        ("statutory", "Statutory charges"),
        ("payment", "Payment options"),
    )
    hits = [(low.index(n), label) for n, label in needles if n in low]
    if hits:
        label = min(hits)[1]
        return label, slug(label), limit, optional
    return name.strip(), slug(name), limit, optional


def as_xml_html(raw):
    """Re-serialise editor HTML as well-formed XML for an html field."""
    if not raw:
        return ""
    try:
        from lxml import etree, html as lhtml
    except ImportError:  # fall back to escaping; the field then needs a fix-up
        return escape(raw)
    fragment = lhtml.fragment_fromstring(raw, create_parent="div")
    out = etree.tostring(fragment, encoding="unicode", method="xml")
    return out[len("<div>"):-len("</div>")] if out.startswith("<div>") else out


def field(name, value=None, ref=None, eval_=None, type_=None):
    if ref is not None:
        return '        <field name="%s" ref="%s"/>\n' % (name, ref)
    if eval_ is not None:
        return '        <field name="%s" eval=%s/>\n' % (name, quoteattr(eval_))
    if type_ == "html":
        return '        <field name="%s" type="html">%s</field>\n' % (name, value)
    return '        <field name="%s">%s</field>\n' % (name, escape(str(value)))


# ---------------------------------------------------------------- categories

def write_categories(categories):
    body = HEADER
    for cat in categories:
        xmlid = "categ_%s" % slug(cat["complete_name"].replace("Insurance Premiums", "ins"))
        body += '    <record id="%s" model="product.category">\n' % xmlid
        body += field("name", cat["name"])
        if cat["parent_id"]:
            parent = next(c for c in categories if c["id"] == cat["parent_id"][0])
            body += field("parent_id", ref="categ_%s" % slug(
                parent["complete_name"].replace("Insurance Premiums", "ins")))
        body += "    </record>\n\n"
    body += FOOTER
    open(os.path.join(OUT, "product_category.xml"), "w", encoding="utf-8").write(body)
    return {c["id"]: "categ_%s" % slug(c["complete_name"].replace("Insurance Premiums", "ins"))
            for c in categories}


# --------------------------------------------------------------------- taxes

def write_taxes():
    body = HEADER
    body += '    <record id="tax_group_insurance_levies" model="account.tax.group">\n'
    body += field("name", "Insurance Levies")
    body += field("sequence", 50)
    body += "    </record>\n\n"
    for xmlid, name, amount, note in (
        ("tax_training_levy", "Training Levy 0.2%", 0.2,
         "Insurance Training Levy &#8211; 0.2% of basic premium"),
        ("tax_phcf", "PHCF 0.25%", 0.25,
         "Policyholders' Compensation Fund levy &#8211; 0.25% of basic premium"),
    ):
        body += '    <record id="%s" model="account.tax">\n' % xmlid
        body += field("name", name)
        body += field("amount", amount)
        body += field("amount_type", "percent")
        body += field("type_tax_use", "sale")
        body += field("price_include_override", "tax_excluded")
        body += field("tax_group_id", ref="tax_group_insurance_levies")
        body += field("country_id", ref="base.ke")
        body += '        <field name="description" type="html"><div>%s</div></field>\n' % note
        body += "    </record>\n\n"
    body += FOOTER
    open(os.path.join(OUT, "account_tax.xml"), "w", encoding="utf-8").write(body)


# ------------------------------------------------------------------ products

#: The catalogue is the office's once installed: staff keep rates in Cover
#: Quotes > Products, and an upgrade must never put the shipped ones back.
CATALOGUE_HEADER = HEADER.replace("<odoo>", '<odoo noupdate="1">')


def write_products(products, cat_xmlids):
    """Written as product.product: it delegates to product.template via
    _inherits, so one record creates both, and template lines can point at it."""
    body = CATALOGUE_HEADER
    seen = {}
    for prod in products:
        xmlid = "prod_%s" % slug(prod["default_code"])
        if xmlid in seen:
            raise SystemExit("external id collision: %s and %s both give %s"
                             % (seen[xmlid], prod["default_code"], xmlid))
        seen[xmlid] = prod["default_code"]
        body += '    <record id="%s" model="product.product">\n' % xmlid
        body += field("name", prod["name"])
        body += field("default_code", prod["default_code"])
        body += field("type", "service")
        body += field("list_price", prod["list_price"])
        body += field("sale_ok", eval_="True" if prod["sale_ok"] else "False")
        body += field("purchase_ok", eval_="False")
        body += field("invoice_policy", "order")
        # IPF-* carry the cost of paying monthly, not cover. Flagging them keeps
        # them out of the premium an instalment schedule is worked out from, so
        # interest is never charged on interest. FEE-STAMP is a real statutory
        # charge and stays part of the premium.
        if prod["default_code"].startswith("IPF-"):
            body += field("odin_instalment_interest", eval_="True")
        body += field("uom_id", ref="uom.product_uom_unit")
        if prod["categ_id"]:
            body += field("categ_id", ref=cat_xmlids[prod["categ_id"][0]])
        if prod.get("description_sale"):
            body += field("description_sale", prod["description_sale"])
        if prod["taxes_id"]:
            body += field("taxes_id", eval_=
                          "[(6, 0, [ref('tax_training_levy'), ref('tax_phcf')])]")
        else:
            body += field("taxes_id", eval_="[(5, 0, 0)]")
        body += "    </record>\n\n"
    body += FOOTER
    open(os.path.join(OUT, "product_template.xml"), "w", encoding="utf-8").write(body)
    # keyed by product code: template lines reference product.product ids,
    # which are not the same numbers as product.template ids
    return {p["default_code"]: "prod_%s" % slug(p["default_code"]) for p in products}


# ------------------------------------------------------------------ insurers

def write_insurers():
    """The insurers as contacts. noupdate: their address and phone are the
    team's to keep, and an upgrade must not put back what they changed."""
    body = HEADER.replace("<odoo>", '<odoo noupdate="1">')
    for _prefix, xmlid, name in INSURERS:
        body += '    <record id="%s" model="res.partner">\n' % xmlid
        body += field("name", name)
        body += field("is_company", eval_="True")
        body += field("country_id", ref="base.ke")
        body += "    </record>\n\n"
    body += FOOTER
    open(os.path.join(OUT, "insurer.xml"), "w", encoding="utf-8").write(body)


def key_terms_of(template_name):
    """Which key terms (tools/key_terms.py) a catalogue plan prints."""
    if template_name.startswith("APA Jamii Plus – Child-Only"):
        return "apa_child_only"
    if template_name.startswith("APA Jamii Plus"):
        return "apa_family"
    if template_name.startswith("Birdview Bizsure Afya"):
        return "birdview"
    raise SystemExit("no key terms for %s: add them to tools/key_terms.py" % template_name)


def insurer_of(template_name):
    return next((xmlid for prefix, xmlid, _name in INSURERS
                 if template_name.startswith(prefix)), None)


# ------------------------------------------------------ APA notes, by limit
#
# APA's outpatient benefits differ by limit, and its child-only plan's
# inpatient benefits by inpatient limit. Their long terms printed every limit
# in a table; the key terms do not, so each limit gets its own note, titled
# "... on the KES 50,000 limit", and a quotation keeps only the note of the
# limit quoted (odin_medical_quote's NOTE_LIMIT).

#: a template note that pointed to the long terms for the benefits by limit
OUTPATIENT_POINTER = ("Outpatient cover is priced per person", "Benefits for each outpatient limit")
CHILD_INPATIENT_POINTER = "Child-only cover is available for inpatient limits"


def limit_title(what, limit):
    return "%s benefits on the KES %s limit" % (what, "{:,.0f}".format(limit))


def amount_text(cell):
    """``2,000`` -> ``KES 2,000``; ``Up to 4,000`` -> ``up to KES 4,000``."""
    found = re.fullmatch(r"(Up to )?([\d,]+)", cell.strip(), re.I)
    if not found:
        raise SystemExit("APA outpatient table: cannot read %r" % cell)
    return "%sKES %s" % ("up to " if found.group(1) else "", found.group(2))


def apa_outpatient_notes(note_html):
    """One note per outpatient limit, from the table of APA's long terms."""
    from lxml import html as lhtml
    doc = lhtml.fromstring("<div>%s</div>" % note_html)
    rows = None
    for table in doc.iter("table"):
        found = [[cell.text_content().strip() for cell in row] for row in table.iter("tr")]
        if found and found[0][0] == "Outpatient benefit":
            rows = found
    also = next((" ".join(p.text_content().split()) for p in doc.iter("p")
                 if "Also covered at every level:" in p.text_content()), "")
    if not rows or not also:
        raise SystemExit("APA terms: the outpatient benefits table has moved")
    also = also.split("Also covered at every level:", 1)[1].strip().rstrip(".")
    notes = []
    for column, head in enumerate(rows[0][1:], start=1):
        limit = float(head.replace(",", ""))
        lines = [limit_title("Outpatient", limit),
                 "• Limit: KES %s per person per year, the same for every member"
                 % "{:,.0f}".format(limit)]
        lines += ["• %s: %s" % (row[0], amount_text(row[column])) for row in rows[1:]]
        lines += ["• Also covered: %s" % also,
                  "• Co-payments at some hospitals: see Co-payments in the terms"]
        notes.append((limit, "\n".join(lines)))
    return notes


def apa_child_inpatient_notes(lines, templates):
    """The family plans' inpatient notes, one per limit, for the child-only
    plan: the benefits are the same, the joining ages are the parents'."""
    names = {t["id"]: t["name"] for t in templates}
    notes = []
    for line in lines:
        name = names.get(line["sale_order_template_id"][0], "")
        found = re.fullmatch(r"APA Jamii Plus – Family Cover \(KES ([\d,]+)\)", name)
        text = line["name"] or ""
        if found and line["display_type"] == "line_note" and text.startswith("Inpatient benefits"):
            limit = float(found.group(1).replace(",", ""))
            body = [part for part in text.splitlines()[1:]
                    if not part.startswith("Principal and spouse can join")]
            notes.append((limit, "\n".join([limit_title("Inpatient", limit)] + body)))
    if len(notes) != 7:
        raise SystemExit("APA child-only: expected 7 family inpatient notes, found %d" % len(notes))
    return sorted(notes)


def by_limit(line, notes, tag):
    """The template note ``line`` as one note per limit: the first keeps its
    external id, the others take the limit after it."""
    out = []
    for index, (limit, text) in enumerate(notes):
        copy = dict(line, name=text)
        if index:
            copy["xml_suffix"] = "_%s%dk" % (tag, limit // 1000)
        out.append(copy)
    return out


def rework_apa_notes(tmpl, tmpl_lines, lines, templates):
    if not tmpl["name"].startswith("APA Jamii Plus"):
        return tmpl_lines
    out = []
    for line in tmpl_lines:
        text = line["name"] or ""
        if line["display_type"] == "line_note" and text.startswith(OUTPATIENT_POINTER):
            out += by_limit(line, apa_outpatient_notes(tmpl["note"]), "op")
        elif line["display_type"] == "line_note" and text.startswith(CHILD_INPATIENT_POINTER):
            out += by_limit(line, apa_child_inpatient_notes(lines, templates), "ip")
        else:
            out.append(line)
    return out


# ----------------------------------------------------------------- templates

def write_templates(templates, lines, prod_xmlids):
    by_template = {}
    for line in lines:
        by_template.setdefault(line["sale_order_template_id"][0], []).append(line)

    body = CATALOGUE_HEADER
    for tmpl in sorted(templates, key=lambda t: t["sequence"]):
        xmlid = "sot_%s" % slug(tmpl["name"])
        body += '    <record id="%s" model="sale.order.template">\n' % xmlid
        body += field("name", tmpl["name"])
        body += field("sequence", tmpl["sequence"])
        body += field("number_of_days", tmpl["number_of_days"])
        body += field("require_signature", eval_="True" if tmpl["require_signature"] else "False")
        body += field("require_payment", eval_="True" if tmpl["require_payment"] else "False")
        # The quotation prints the plan's key terms, not the long terms the
        # catalogue was first loaded with (data/source keeps those).
        body += field("note", key_terms.html(key_terms_of(tmpl["name"])), type_="html")
        body += field("odin_medical", eval_="True")
        insurer = insurer_of(tmpl["name"])
        if insurer:
            body += field("odin_insurer_id", ref=insurer)
        body += "    </record>\n\n"

        tmpl_lines = sorted(by_template.get(tmpl["id"], []), key=lambda l: (l["sequence"], l["id"]))
        for line in rework_apa_notes(tmpl, tmpl_lines, lines, templates):
            # Named after the rate card's own line id, not its position: a
            # position shifts when a line is inserted, and an upgrade would
            # then rewrite a note into a product line, which Odoo refuses.
            line_id = "%s_line_%d%s" % (xmlid, line["id"], line.get("xml_suffix", ""))
            body += '    <record id="%s" model="sale.order.template.line">\n' % line_id
            body += field("sale_order_template_id", ref=xmlid)
            body += field("sequence", line["sequence"])
            if line["display_type"]:
                body += field("display_type", line["display_type"])
            if line["name"]:
                body += field("name", line["name"])
            if line["product_id"]:
                code = line["product_code"]
                body += field("product_id", ref=prod_xmlids[code])
                body += field("product_uom_id", ref="uom.product_uom_unit")
            body += field("product_uom_qty", line["product_uom_qty"])
            if line["display_type"] == "line_section":
                label, key, limit, optional = benefit_of(line["name"])
                body += field("benefit_label", label)
                body += field("benefit_key", key)
                if limit:
                    body += field("cover_limit", limit)
                if optional:
                    body += field("is_optional", eval_="True")
            body += "    </record>\n\n"
    body += FOOTER
    open(os.path.join(OUT, "sale_order_template.xml"), "w", encoding="utf-8").write(body)


def main():
    categories = load("product_category.json")
    products = load("product_template.json")
    templates = load("sale_order_template.json")
    lines = load("sale_order_template_line.json")

    cat_xmlids = write_categories(categories)
    write_taxes()
    write_insurers()
    prod_xmlids = write_products(products, cat_xmlids)
    write_templates(templates, lines, prod_xmlids)
    print("categories %d | products %d | templates %d | template lines %d"
          % (len(categories), len(products), len(templates), len(lines)))


if __name__ == "__main__":
    main()
